"""
cli.py
~~~~~~
CLI de gestión de clientes jota-gateway.
Uso: python src/cli.py <command> [options]
"""

import argparse
import secrets
import sys
from typing import get_args

from pydantic import TypeAdapter, ValidationError
from sqlmodel import Session, select

from src.core.logging import fingerprint_key
from src.db.database import get_engine, run_migrations
from src.db.models import ClientRecord
from src.models.admin_schemas import AgentName, ClientType

_AGENT = TypeAdapter(AgentName)


def _get_engine():
    """Indirection para monkeypatching en tests."""
    return get_engine()


def _agent(value: str) -> str:
    """--agent con la misma validación que el admin REST (#233, #239): recorte, no vacío."""
    try:
        return _AGENT.validate_python(value)
    except ValidationError:
        raise argparse.ArgumentTypeError("vacío o de más de 200 caracteres") from None


def _require(session: Session, client_key: str) -> ClientRecord:
    rec = session.exec(select(ClientRecord).where(ClientRecord.client_key == client_key)).first()
    if rec is None:
        # G-27c (#216): la key es una credencial; solo su huella (la misma `fp=` de los logs).
        print(
            f"ERROR: No se encontró cliente con esa key (fp={fingerprint_key(client_key)})",
            file=sys.stderr,
        )
        sys.exit(1)
    return rec


def cmd_add(
    name: str, client_type: str | None, agent: str | None, engine, client_key: str | None = None
) -> None:
    key = client_key or secrets.token_urlsafe(32)
    with Session(engine) as s:
        rec = ClientRecord(name=name, client_key=key, client_type=client_type, default_agent=agent)
        s.add(rec)
        s.commit()
        s.refresh(rec)
    print("Cliente creado:")
    print(f"  name:       {rec.name}")
    print(f"  id:         {rec.id}")
    print(f"  client_key: {rec.client_key}")


def cmd_list(engine) -> None:
    with Session(engine) as s:
        records = s.exec(select(ClientRecord)).all()
    if not records:
        print("(sin clientes)")
        return
    # G-27c (#216): ni un prefijo de la key (20 chars son ~120 bits de una de 256). El
    # operador identifica por ID/NAME y correlaciona con los logs por la huella `fp`.
    fmt = "{:<36}  {:<20}  {:<8}  {}"
    print(fmt.format("ID", "NAME", "ACTIVE", "KEY FP (sha256[:8])"))
    print("-" * 90)
    for r in records:
        print(fmt.format(r.id, r.name[:20], str(r.is_active), fingerprint_key(r.client_key)))


def cmd_deactivate(client_key: str, engine) -> None:
    with Session(engine) as s:
        rec = _require(s, client_key)
        rec.is_active = False
        s.add(rec)
        s.commit()
    print("Cliente desactivado.")


def cmd_activate(client_key: str, engine) -> None:
    with Session(engine) as s:
        rec = _require(s, client_key)
        rec.is_active = True
        s.add(rec)
        s.commit()
    print("Cliente activado.")


def cmd_delete(client_key: str, engine) -> None:
    with Session(engine) as s:
        rec = _require(s, client_key)
        s.delete(rec)
        s.commit()
    print("Cliente eliminado.")


def run(argv: list[str]) -> None:
    p = argparse.ArgumentParser(prog="python src/cli.py")
    sub = p.add_subparsers(dest="cmd", required=True)

    a = sub.add_parser("add-client")
    a.add_argument("--name", required=True)
    a.add_argument(
        "--key", dest="client_key", help="client_key exacto a usar (si se omite, se genera uno)"
    )
    a.add_argument("--type", dest="client_type", choices=get_args(ClientType))
    a.add_argument("--agent", type=_agent)

    sub.add_parser("list-clients")

    for name in ("deactivate-client", "activate-client", "delete-client"):
        sp = sub.add_parser(name)
        sp.add_argument("client_key")

    # client_key is opaque (secrets.token_urlsafe-generated by default) and
    # can start with '-', which argparse would otherwise misread as an
    # unknown option instead of the positional value ("the following
    # arguments are required: client_key"). Force positional parsing for it
    # by inserting `--` right after the subcommand name.
    if (
        len(argv) >= 2
        and argv[0] in ("deactivate-client", "activate-client", "delete-client")
        and argv[1] != "--"
    ):
        argv = [argv[0], "--", *argv[1:]]

    args = p.parse_args(argv)
    engine = _get_engine()

    if args.cmd == "add-client":
        cmd_add(args.name, args.client_type, args.agent, engine, args.client_key)
    elif args.cmd == "list-clients":
        cmd_list(engine)
    elif args.cmd == "deactivate-client":
        cmd_deactivate(args.client_key, engine)
    elif args.cmd == "activate-client":
        cmd_activate(args.client_key, engine)
    elif args.cmd == "delete-client":
        cmd_delete(args.client_key, engine)


if __name__ == "__main__":
    run_migrations()
    run(sys.argv[1:])
